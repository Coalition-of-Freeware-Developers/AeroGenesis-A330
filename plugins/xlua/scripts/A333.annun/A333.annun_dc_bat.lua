local function A333_annun_dc_bat_cache_globals()

    lcl_SIM_PERIOD = SIM_PERIOD

    annun_light_switch_dim_or_brt = A333DR_ann_light_switch_pos <= 1
    annun_dc_bat_brightness = A333DR_annun_brightness_dc_bat
    annun_dc_apu_bat_brightness = A333DR_annun_brightness_dc_bat
    annun_light_switch_test = A333DR_dc_bus2_has_power

end




local function A333_annun_dc_bat_processing()

    -- SET ANNUNCIATOR STATUS (0/1)
    local bat1_off_annun_target = annun_light_switch_dim_or_brt and bool2num[A333DR_buttons_battery1_ctct_on_off == 0] or annun_light_switch_test
    local bat2_off_annun_target = annun_light_switch_dim_or_brt and bool2num[A333DR_buttons_battery2_ctct_on_off == 0] or annun_light_switch_test
    local apu_bat_off_annun_target = annun_light_switch_dim_or_brt and bool2num[A333DR_buttons_apu_bat_ctct_on_off == 0] or annun_light_switch_test


    -- SET ANNUNCIATOR FADE IN/OUT
    annun_bat1_off = animate(annun_bat1_off, bat1_off_annun_target, 13)
    annun_bat2_off = animate(annun_bat2_off, bat2_off_annun_target, 13)
    annun_apu_bat_off = animate(annun_apu_bat_off, apu_bat_off_annun_target, 13)


    -- SET ANNUNCIATOR BRIGHTNESS AND ASSIGN TO DATAREF
    A333DR_annun_elec_bat1_off = annun_bat1_off * annun_dc_bat_brightness
    A333DR_annun_elec_bat2_off = annun_bat2_off * annun_dc_bat_brightness
    A333DR_annun_elec_apu_bat_off = annun_apu_bat_off * annun_dc_bat_brightness

end



