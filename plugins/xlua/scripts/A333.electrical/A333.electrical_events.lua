--===| FLIGHT START |====================================================================
function flight_start()

    A333_elec_flight_start()

    if simDR_startup_running == 0 then A333_elec_flight_start_CD() end
    if simDR_startup_running == 1 then A333_elec_flight_start_ER() end
    run_after_time(A333_elec_deferred_init, 2.0)
    run_after_time(function() deferred_processing = true end, 3.0)

end



