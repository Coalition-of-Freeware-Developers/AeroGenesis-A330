local function A333_resetClearedSDmessages()
    for _, sts in pairs(A333_sts_msg) do
        if sts.Video.OUT == 2 then
            sts.Video.OUT = 1
            for _, msg in ipairs(sts.Msg) do
                if msg.Cleared == 1 then
                    msg.Cleared = 0
                end
            end
        end
    end
end




local function A333_fws_status_page_manager()

	local a = ZASTSPD or ZMSTSPD or ZSTSCAPPR
	sp_pulse01:update(a)
	local b = (not ZASTSPD and not ZMSTSPD and not ZSTSCAPPR)
	sp_SRRlatch01:update(sp_pulse01.OUT, b)

	ZSTSPD = sp_SRRlatch01.Q

	A333_ecam_status_system_page_num = 15 * bool2num[ZSTSPD]




	-- RESET THE CLEARED MESSAGES WHEN STATUS PAGE IS NO LONGER DISPLAYED
	if not ZSTSPD then											-- STATUS PAGE IS CLOSED
		if not SDmsgsAreReset then								-- SD MESSAGES ARE NOT RESET
			A333_resetClearedSDmessages()						-- RESET THE SD MESSSAGES
			SDmsgsAreReset = true								-- SET THE FLAG
		end
	else														-- STATUS PAGE IS OPEN
		if SDmsgsAreReset then									-- IF MESSAGES ARE RESET
			SDmsgsAreReset = false								-- CHANGE RESET FLAG
		end
	end

end




local function A333_fws_sts_annun()
    A333DR_ecp_sts_pushbutton_annun = bool2num[ZSTSPD]
end












function A333_resetManualStatusPageData()
	ZMSTSPD = false
	A333_resetClearedSDmessages()
end





